// F. Hirzebruch, "Hilbert's modular group of the field Q(sqrt5) and the cubic
// diagonal surface of Clebsch and Klein", Russian Math. Surveys 31:5 (1976),
// 96-110, Theorem 2, p.108, equation (15).
//
// Theorem 2 presents the even-weight ring M(Gamma(2)) over C.
// Over Q we take Q[E0,...,E4]/(sigma2,sigma4), with generators of weight 2.
// M(Gamma0((2))) = M(Gamma(2))^A4, with A4 fixing the cusp at infinity.
//
// The stored witness maps match these invariants over Q to
// Verification/CanonicalRingEquations/2.2.5.1-4.1-gl-0.m.
LitData := function(Rsrc, Rtgt)
  weights := [2, 2, 6, 12];
  assert VariableWeights(Rsrc) eq weights;
  assert VariableWeights(Rtgt) eq weights;
  P<[E]> := PolynomialRing(Rationals(), [2, 2, 2, 2, 2]);
  sigma := func< xs,k | &+[Parent(xs[1]) |
    &*[xs[i] : i in s] : s in Subsets({1..#xs},k)] >;
  principal := ideal<P | sigma(E,2), sigma(E,4)>;
  assert IsHomogeneous(principal);

  // E0 is 1 at infinity and 0 at the other cusps (pp.107-108).
  // The Borel stabilizer A4 of this cusp acts by even permutations of E1,...,E4.
  G := sub<Sym(5) | (2,3,4), (2,3)(4,5)>;
  assert #G eq 12 and &and[1^g eq 1 : g in G];
  e := E[1];
  a := sigma(E[2..5],1);
  c := sigma(E[2..5],3);
  delta := &*[P | E[i]-E[j] : i,j in [2..5] | i lt j];
  invariants := [e,a,c,delta];
  assert &and[Evaluate(f,[P.(i^g) : i in [1..5]]) eq f
    : f in invariants, g in Generators(G)];
  assert sigma(E[2..5],2)+e*a in principal;
  assert sigma(E[2..5],4)+e*c in principal;

  // Alternating polynomials are symmetric polynomials times delta.
  // Thus A4 invariants are generated by E0, the elementary symmetric functions
  // of E1,...,E4 and delta; sigma2=sigma4=0 eliminate the second and fourth.
  u := Rsrc.1; v := Rsrc.2; w := Rsrc.3; z := Rsrc.4;
  U<T> := PolynomialRing(Rsrc);
  quartic := T^4-v*T^3-u*v*T^2-w*T-u*w;
  I := ideal<Rsrc | z^2-Discriminant(quartic)>;
  assert IsHomogeneous(I);
  assert WeightedDegree(Generators(I)[1]) eq 24;
  assert Evaluate(Generators(I)[1],invariants) in principal;

  // The Molien series certifies that the discriminant is the entire kernel.
  Qq<q> := RationalFunctionField(Rationals());
  molien := (1/(1-q^2)^5 + 3/((1-q^2)*(1-q^4)^2)
    + 8/((1-q^2)^2*(1-q^6)))/12*(1-q^4)*(1-q^8);
  assert Qq!HilbertSeries(I) eq molien;

  x := [Rtgt.i : i in [1..Rank(Rtgt)]];
  PhiImages := [ Rtgt |
    -1/480*x[1] + 1/30*x[2],
    1/30*x[1] - 1/30*x[2],
    1/1152000*x[1]^3 - 13/1152000*x[1]^2*x[2] + 23/1152000*x[1]*x[2]^2 - 11/1152000*x[2]^3 +
      1/2*x[3],
    -1/530841600000*x[1]^6 + 1/31850496000*x[1]^5*x[2] - 89/318504960000*x[1]^4*x[2]^2 +
      67/79626240000*x[1]^3*x[2]^3 - 361/318504960000*x[1]^2*x[2]^4 + 569/796262400000*x[1]*x[2]^5 -
      11/63700992000*x[2]^6 - 1/6912000*x[1]^3*x[3] + 31/2304000*x[1]^2*x[2]*x[3] +
      239/2304000*x[1]*x[2]^2*x[3] - 809/6912000*x[2]^3*x[3] - 1/8*x[3]^2 - 1/32*x[4]
  ];
  x := [Rsrc.i : i in [1..Rank(Rsrc)]];
  PsiImages := [ Rsrc |
    32*x[1] + 32*x[2],
    32*x[1] + 2*x[2],
    1/2*x[1]*x[2]^2 - 1/64*x[2]^3 + 2*x[3],
    64*x[1]^3*x[2]^3 + 7*x[1]^2*x[2]^4 + 3/16*x[1]*x[2]^5 - 3/64*x[2]^6 + 256*x[1]^2*x[2]*x[3] +
      48*x[1]*x[2]^2*x[3] + 5/2*x[2]^3*x[3] - 16*x[3]^2 - 32*x[4]
  ];
  citation := "the A4 invariants of Hirzebruch, Russian Math. Surveys 31:5 (1976), Theorem 2, p.108";
  return I, PhiImages, PsiImages, citation;
end function;
return LitData;
