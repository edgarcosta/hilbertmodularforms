// G. van der Geer, Hilbert Modular Surfaces, Springer Ergebnisse 16 (1988),
// VIII.2.8-2.9, pp.194-195: sigma1=0, f^2=sigma4, g^2=sigma3^2-4*sigma2*sigma4.
// F. Hirzebruch, LNM 627 (1977), Sec.4, pp.314-316, (19)-(22), gives the S4 action.
//
// The image of Gamma0(p2) in SL2(O/(2)) has order 16.
// Its quotient by alpha, the center of SL2(O/(2)), is D8.
// alpha negates f and g; h=f*g descends. Use h^2=-sigma4*(sigma3^2-4*sigma2*sigma4),
// the rational sign certified in 2.2.8.1-1.1-Hirzebruch.m. This records the twist
// separately from van der Geer's printed complex presentation.
//
// D8 stabilizes {1,2}|{3,4}, acts by x_i -> sign(s)*x_(s(i)), and fixes h
// (Hirzebruch, p.316).
// With u=x1+x2, v=x1-x2, w=x3-x4 and sigma1=0, its polynomial invariants are
// a=u^2, b=v^2+w^2, c=v^2*w^2, z=u*v*w*(v^2-w^2), with z^2=a*c*(b^2-4*c).
// Their Molien series is (1+q^5)/((1-q^2)^2*(1-q^4)).
//
// Adjoining h (weight 5) and taking even weight retains t=z*h (weight 10).
// Thus the even invariant ring is generated by a,b,c,t with the relation below.
// Its Hilbert series is (1+q^10)/((1-q^2)^2*(1-q^4)).
//
// eval-loaded: `LitData := eval (Read(<this file>) cat "return LitData;");`
// Call with source and target rings S and R of weights [2,2,4,10]:
// `I, PhiImages, PsiImages, citation := LitData(S, R);`
LitData := function(Rsrc, Rtgt)
  weights := [2, 2, 4, 10];
  assert VariableWeights(Rsrc) eq weights;
  assert VariableWeights(Rtgt) eq weights;
  a := Rsrc.1; b := Rsrc.2; c := Rsrc.3; t := Rsrc.4;
  branch := a*c*(b^2 - 4*c)*(a^2 - a*b + c)*(2*a - b)*(a^2 - c)/256;
  I := ideal<Rsrc | t^2 + branch>;

  y1 := Rtgt.1; y2 := Rtgt.2; y3 := Rtgt.3; y4 := Rtgt.4;
  PhiImages := [Rtgt |
    y1 - 4*y2,
    -2*y1 - 4*y2,
    -y1^2 + 8*y1*y2 + 2*y2^2 - 2304*y3,
    -29/32*y1^5 + 193/32*y1^4*y2 - 241/16*y1^3*y2^2 + 289/16*y1^2*y2^3
      - 337/32*y1*y2^4 + 77/32*y2^5 - 558*y1^3*y3 + 7722*y1^2*y2*y3
      - 24138*y1*y2^2*y3 + 16974*y2^3*y3 - 580608*y1*y3^2 + 1575936*y2*y3^2 + 995328*y4
  ];
  PsiImages := [Rsrc | p : p in GradedInverseImages(Rtgt, PhiImages)];

  citation := "van der Geer, Hilbert Modular Surfaces (1988), VIII.2.9, p.195"
    cat " (even Gamma0(p2) invariants, rational sign h^2=-C)";
  return I, PhiImages, PsiImages, citation;
end function;
return LitData;
