// I is homogeneous, so the class of f is homogeneous of weight w exactly when the
// components of f of other weights lie in I.
function graded_representatives(I, images, weights)
  R := Generic(I);
  graded := [R |];
  for i in [1..#images] do
    ok, f := IsCoercible(R, images[i]);
    if not ok then return false, [R |]; end if;
    g := HomogeneousComponent(f, weights[i]);
    if f - g notin I then return false, [R |]; end if;
    Append(~graded, g);
  end for;
  return true, graded;
end function;

function symmetric_action_is_valid(I, images)
  R := Generic(I);
  if BaseRing(R) cmpne Rationals() or
      &or[w le 0 : w in VariableWeights(R)] or
      not IsHomogeneous(I) or R!1 in I or #images ne Rank(R) then
    return false, [R |];
  end if;
  ok, graded := graded_representatives(I, images, VariableWeights(R));
  if not ok then return false, graded; end if;
  tau := hom<R -> R | graded>;
  return &and[tau(f) in I : f in Basis(I)] and
      &and[tau(tau(R.i)) - R.i in I : i in [1..Rank(R)]], graded;
end function;

// Relations in generator weights must be included in the graded piece of R/I.
function symmetric_expression(I, images, f)
  R := Generic(I);
  f := NormalForm(f, I);
  if IsEmpty(images) then
    return f eq 0, Rationals()!0;
  end if;
  P := PolynomialRing(Rationals(), [WeightedDegree(g) : g in images]);
  if f eq 0 then return true, P!0; end if;
  w := WeightedDegree(f);
  mons := Setseq(MonomialsOfWeightedDegree(P, w));
  ambient := Setseq(MonomialsOfWeightedDegree(R, w));
  rows := [NormalForm(Evaluate(m, images), I) : m in mons];
  mat := Matrix(Rationals(), #rows, #ambient,
      &cat[[MonomialCoefficient(g, m) : m in ambient] : g in rows]);
  rhs := Vector(Rationals(), [MonomialCoefficient(f, m) : m in ambient]);
  ok, sol := IsConsistent(mat, rhs);
  if not ok then return false, P!0; end if;
  expression := &+[P | sol[i]*mons[i] : i in [1..#mons]];
  assert Evaluate(expression, images) - f in I;
  return true, expression;
end function;

function symmetric_graph_kernel(I, P, images)
  R := Generic(I);
  T := PolynomialRing(Rationals(), Rank(R) + Rank(P), "lex");
  target := hom<R -> T | [T.i : i in [1..Rank(R)]]>;
  graph := ideal<T | [target(g) : g in Basis(I)] cat
      [T.(Rank(R) + i) - target(images[i]) : i in [1..Rank(P)]]>;
  E := EliminationIdeal(graph, Rank(R));
  project := hom<T -> P | [P!0 : i in [1..Rank(R)]] cat
      [P.i : i in [1..Rank(P)]]>;
  return ideal<P | [project(g) : g in Basis(E)]>;
end function;

// Averaging an equivariant polynomial presentation shows that these elements
// generate the fixed ring, even when the action on the original variables is nonlinear.
function symmetric_classical_generators(R, tau)
  plus := [R.i + tau(R.i) : i in [1..Rank(R)]];
  minus := [R.i - tau(R.i) : i in [1..Rank(R)]];
  return plus cat [minus[i]*minus[j] : j in [i..Rank(R)], i in [1..Rank(R)]];
end function;

intrinsic IsSymmetricSubringPresentation(I::RngMPol, swap_images::SeqEnum,
    K::RngMPol, inclusion_images::SeqEnum) -> BoolElt
{A test that K and inclusion_images present the subring of Generic(I)/I fixed
 by the graded involution with images swap_images over the rationals.
 See also SymmetricSubringPresentation}
  R := Generic(I); P := Generic(K);
  ok, action := symmetric_action_is_valid(I, swap_images);
  if not ok or BaseRing(P) cmpne Rationals() or not IsHomogeneous(K) or
      &or[w le 0 : w in VariableWeights(P)] or
      #inclusion_images ne Rank(P) then
    return false;
  end if;
  tau := hom<R -> R | action>;
  ok, images := graded_representatives(I, inclusion_images, VariableWeights(P));
  if not ok then return false; end if;
  for f in images do
    if tau(f) - f notin I then return false; end if;
  end for;
  if symmetric_graph_kernel(I, P, images) ne K then return false; end if;
  nonzero := [f : f in images | f ne 0];
  for f in symmetric_classical_generators(R, tau) do
    ok, expression := symmetric_expression(I, nonzero, f);
    if not ok then return false; end if;
  end for;
  return true;
end intrinsic;

intrinsic SymmetricSubringPresentation(I::RngMPol, swap_images::SeqEnum)
    -> RngMPol, SeqEnum, FldFunRatUElt
{A relation ideal, inclusion images and Hilbert series for the subring of
 Generic(I)/I fixed by the graded involution with images swap_images over the rationals.
 The fixed subring must have a generator of positive degree.
 See also IsSymmetricSubringPresentation}
  ok, action := symmetric_action_is_valid(I, swap_images);
  require ok:
      "Expected a proper homogeneous rational ideal, positive weights, and a " cat
      "graded involution modulo the ideal";
  R := Generic(I);
  tau := hom<R -> R | action>;
  lifts := [R |]; signs := [];
  for w in Sort(Setseq(Seqset(VariableWeights(R)))) do
    // Reynolds projections select an eigenbasis on indecomposables modulo
    // the subalgebra generated by the lifts chosen so far.
    for sign in [1, -1] do
      for i in [j : j in [1..Rank(R)] | WeightedDegree(R.j) eq w] do
        f := (R.i + sign*tau(R.i))/2;
        ok, expression := symmetric_expression(I, lifts, f);
        if not ok then
          assert tau(f) - sign*f in I;
          Append(~lifts, f); Append(~signs, sign);
        end if;
      end for;
    end for;
  end for;
  reconstruction := [];
  for i in [1..Rank(R)] do
    ok, expression := symmetric_expression(I, lifts, R.i);
    assert ok;
    Append(~reconstruction, expression);
  end for;
  fixed := [lifts[i] : i in [1..#lifts] | signs[i] eq 1];
  skew := [lifts[i] : i in [1..#lifts] | signs[i] eq -1];
  candidates := fixed cat [skew[i]*skew[j] : j in [i..#skew], i in [1..#skew]];
  images := [R |];
  for w in Sort(Setseq({WeightedDegree(f) : f in candidates | f ne 0})) do
    for f in [g : g in candidates | g ne 0 and WeightedDegree(g) eq w] do
      ok, expression := symmetric_expression(I, images, f);
      if not ok then Append(~images, f); end if;
    end for;
  end for;
  witnesses := candidates cat symmetric_classical_generators(R, tau);
  certificates := [];
  for f in witnesses do
    ok, expression := symmetric_expression(I, images, f);
    assert ok;
    Append(~certificates, expression);
  end for;
  require not IsEmpty(images): "The fixed algebra has no positive-degree generators";
  P := PolynomialRing(Rationals(), [WeightedDegree(f) : f in images]);
  K := symmetric_graph_kernel(I, P, images);
  assert &and[Evaluate(reconstruction[i], lifts) - R.i in I : i in [1..Rank(R)]];
  assert &and[Evaluate(certificates[i], images) - witnesses[i] in I :
      i in [1..#witnesses]];
  H := FunctionField(Rationals());
  return K, images, H!HilbertSeries(K);
end intrinsic;

function is_geometric_swap(M, N, G, I, tau, weights, precision)
  R := Generic(I);
  if #tau ne Rank(R) or not Keys(G) subset Seqset(weights) then
    return false;
  end if;
  for w in weights do
    space := HMFSpace(M, N, [w, w]);
    if not &and[IsOne(u) : u in Values(UnitCharacters(space))] then
      return false;
    end if;
    mons := Setseq(MonomialsOfWeightedDegree(R, w));
    forms := EvaluateMonomials(G, mons);
    extra := IsDefined(G, w) select [Swap(g) : g in G[w]] else [];
    coeffs := CoefficientsMatrix(forms cat extra : prec := precision);
    A := RowSubmatrix(coeffs, 1, #forms);
    // Rank(A) = dim M_w proves spanning and injective truncation at precision.
    // Equal truncated rows therefore prove equality of forms in M_w.
    known := Dimension(space);
    if Rank(A) ne known or Rank(coeffs) ne known then return false; end if;
    row := func<f | Vector(BaseRing(A), [MonomialCoefficient(f, m) : m in mons])>;
    if &or[row(f)*A ne 0 : f in Basis(I) | WeightedDegree(f) eq w] then
      return false;
    end if;
    offset := #[v : v in VariableWeights(R) | v lt w];
    for j in [1..#extra] do
      f := tau[offset + j];
      if not IsHomogeneous(f) or row(f)*A ne coeffs[#forms + j] then
        return false;
      end if;
    end for;
  end for;
  return true;
end function;
